function sampleTask(id: string, scenarioIndex: number, createdAt: number): Task {
  const sc = TEMPLATES[scenarioIndex];
  return { id, title: sc.title, goal: sc.goal, createdAt, updatedAt: createdAt, scenarioId: sc.id, agentIds: sc.agents, runIds: [], messages: [], source: 'sample' };
}

/** Fresh state with three sample tasks: one completed, one failed (retry-able), one cancelled. */
export function seededState(now: number, settings: Settings = DEFAULT_SETTINGS): AppState {
  return produce(emptyState(now, { ...settings, injectFailure: true }), (d) => {
    const hour = 3_600_000;
    const plan: Array<[number, number, 'complete' | { cancelAtStep: number }]> = [
      [2, now - 26 * hour, { cancelAtStep: 2 }],   // 日志周报 · 已取消
      [1, now - 20 * hour, 'complete'],             // 选型调研 · 已完成
      [0, now - 3 * hour, 'complete'],              // 代码重构 · 第 1 次在测试步骤失败
    ];
    for (const [index, at, stop] of plan) {
      const task = sampleTask(uid('task'), index, at - 60_000);
      d.tasks[task.id] = task;
      d.taskOrder.unshift(task.id);
      say(d.tasks[task.id], at - 50_000);
      const end = simulateOffline(d, task.id, at, stop);
      d.tasks[task.id].updatedAt = end;
    }
    d.settings.injectFailure = settings.injectFailure;
  });
}

function say(task: { messages: Task['messages']; goal: string }, at: number) {
  task.messages.push({ id: uid('msg'), role: 'user', text: task.goal, at, simulated: true });
}
